# Exchange rate: 1 USD = 95.09771 INR
# Amount to convert: 5000 INR

exchange_rate = 95.09771
amount_in_inr = 5000

# Convert INR to USD
amount_in_usd = amount_in_inr / exchange_rate

print(f"Amount in INR: {amount_in_inr}")
print(f"Exchange Rate (INR per USD): {exchange_rate}")
print(f"Amount in USD: {amount_in_usd}")